export const STORAGE_KEY_PRELOADED = "stba_preloaded_answers";

export function getStoredPreloadedAnswers(): PreloadedAnswer[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_PRELOADED);
    if (!raw) return DEFAULT_PRELOADED_ANSWERS;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed.slice(0, 4);
    }
  } catch (e) {
    console.warn("Failed to parse preloaded answers from storage:", e);
  }
  return DEFAULT_PRELOADED_ANSWERS;
}

export function savePreloadedAnswer(
  question: string,
  answer: string,
  customTopic?: string,
  customRef?: string
): PreloadedAnswer[] {
  try {
    const current = getStoredPreloadedAnswers();
    
    // Extract topic and reference if not provided
    let topic = customTopic || "";
    let ref = customRef || "";

    if (!ref) {
      // Regex search for common biblical references like Romans 8:1-4, Revelation 14:6, etc.
      const refMatch = answer.match(/([1-3]?\s?[A-Za-z]+)\s+(\d+:\d+(?:[–\-]\d+)?)/);
      if (refMatch) {
        ref = `${refMatch[1]} ${refMatch[2]}`.trim();
      } else {
        ref = "Scripture Exegesis";
      }
    }

    if (!topic) {
      topic = question.replace(/explain|help me understand|test me on|show me every scripture related to/gi, "").trim();
      if (topic.length > 40) {
        topic = topic.slice(0, 40) + "...";
      }
    }

    const newEntry: PreloadedAnswer = {
      id: `ans-${Date.now()}`,
      question: question.trim(),
      topic: topic || "Scripture Exegesis",
      reference: ref,
      answer: answer.trim(),
      date: "Recently Answered",
      isRecent: true
    };

    // Filter out duplicates with the same question (case-insensitive)
    const filtered = current.filter(
      (item) => item.question.toLowerCase().trim() !== question.toLowerCase().trim()
    );

    // Keep exactly 4 items, placing the newest answer at index 0
    const updated = [newEntry, ...filtered].slice(0, 4);
    localStorage.setItem(STORAGE_KEY_PRELOADED, JSON.stringify(updated));
    return updated;
  } catch (err) {
    console.error("Error saving preloaded answer:", err);
    return DEFAULT_PRELOADED_ANSWERS;
  }
}
