export function lookupBiblicalName(word: string): BiblicalName | undefined {
  const clean = word.replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g, "").trim().toLowerCase();
  return BIBLICAL_NAMES_DICTIONARY.find(
    (item) => item.name.toLowerCase() === clean
  );
}

export function detectBiblicalNamesInText(text: string): string[] {
  const words = text.split(/[\s,.;:!?()"-]+/);
  const found: string[] = [];
  words.forEach(w => {
    const clean = w.replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g, "").trim();
    if (clean.length > 2) {
      const match = BIBLICAL_NAMES_DICTIONARY.find(item => item.name.toLowerCase() === clean.toLowerCase());
      if (match && !found.includes(match.name)) {
        found.push(match.name);
      }
    }
  });
  return found;
}
